// يضع الإجابة الصحيحة في الموضع المحدد حتى لا تتكرر في مكان واحد
let cursor = 0
function q(text: string, correct: string, wrong: [string, string], _pos?: 0 | 1 | 2): QuizQuestion {
  const pos = cursor++ % 3 // تدوير الموضع: ٠ ثم ١ ثم ٢ ... فلا تتكرر الإجابة في مكان واحد
  const options = [...wrong]
  options.splice(pos, 0, correct)
  return { q: text, options, answer: pos }
}

