export const KIDS_QUIZ_POOL: QuizQuestion[] = [...KIDS_QUIZ, ...EXTRA]

export const QUIZ_ROUND_SIZE = 10

/** يختار عشرة أسئلة عشوائية مختلفة في كل جولة */
export function pickQuizRound(size = QUIZ_ROUND_SIZE): QuizQuestion[] {
  const a = [...KIDS_QUIZ_POOL]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a.slice(0, size)
}
