const EXCLUDED_HISN_IDS_OR_TITLES = new Set([
  'morning-azkar',
  'evening-azkar',
  'post-prayer-azkar',
])

const OTHER_HISN_CATEGORIES = (HISN_CATEGORIES ?? []).filter((c) => {
  if (!c || !c.id || !c.title) return false
  const lowerId = c.id.toLowerCase()
  if (EXCLUDED_HISN_IDS_OR_TITLES.has(lowerId)) return false
  if (c.title.includes('الصباح والمساء')) return false
  if (c.title.includes('بعد السلام من الصلاة')) return false
  if (lowerId.includes('morning-evening')) return false
  return true
})

const PREFERRED_ORDER = ['أذكار النوم', 'أذكار الاستيقاظ من النوم']

const SORTED_HISN_CATEGORIES = [...OTHER_HISN_CATEGORIES].sort((a, b) => {
  const getPriority = (title: string) => {
    const index = PREFERRED_ORDER.findIndex(
      (t) => title.includes(t) || t.includes(title),
    )
    return index !== -1 ? index : 999
  }
  return getPriority(a.title) - getPriority(b.title)
})

function buildUniqueCategories(categories: DhikrCategory[]): DhikrCategory[] {
  const seenIds = new Set<string>()
  const result: DhikrCategory[] = []

  for (const category of categories) {
    if (!category || !category.id || seenIds.has(category.id)) continue
    seenIds.add(category.id)
    result.push({
      ...category,
      items: deduplicateItems(Array.isArray(category.items) ? category.items : []),
    })
  }

  return result
}

