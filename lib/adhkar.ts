export function getCategory(id: string): DhikrCategory | undefined {
  return ADHKAR.find((c) => c.id === id)
}

export function getCategoriesByGroup(group: DhikrCategory['group']): DhikrCategory[] {
  return ADHKAR.filter((c) => c.group === group)
}

export interface DhikrSearchResult {
  category: DhikrCategory
  dhikr: Dhikr
  itemIndex: number
}

export function searchAdhkar(query: string): DhikrSearchResult[] {
  const normalizedQuery = normalizeText(query)
  if (!normalizedQuery) return []

  const results: DhikrSearchResult[] = []

  for (const category of ADHKAR) {
    category.items.forEach((dhikr, itemIndex) => {
      const haystacks = [
        normalizeText(dhikr.text),
        normalizeText(dhikr.source),
        dhikr.note ? normalizeText(dhikr.note) : '',
        dhikr.fadl ? normalizeText(dhikr.fadl) : '',
        dhikr.occasion ? normalizeText(dhikr.occasion) : '',
        normalizeText(category.title),
      ]

      if (haystacks.some((h) => h.includes(normalizedQuery))) {
        results.push({ category, dhikr, itemIndex })
      }
    })
  }

  return results
}
